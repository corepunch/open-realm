#!/usr/bin/env python3
"""Emit exact C regression inputs from the frozen original region oracle."""
import argparse,gzip,hashlib,itertools,json
from pathlib import Path

def array(name,kind,values):
 result=['static '+kind+' const '+name+'[]={']
 for first in range(0,len(values),16):result.append('    '+','.join(str(x)for x in values[first:first+16])+',')
 result.append('};');return '\n'.join(result)
def runs(values):
 return [n for v,g in itertools.groupby(values)for n in (sum(1 for _ in g),v)]
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--oracle',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args();d=json.loads(gzip.decompress(a.oracle.read_bytes()));q=d['case'];out=['/* Generated by emit_captain369_regions_test.py from original retail captures.', ' * Oracle SHA256 '+hashlib.sha256(a.oracle.read_bytes()).hexdigest()+' */']
 for name,kind,values in [('captain369_class_runs','uint32_t',runs([x>>30 for x in q['cells'][1::2]])),('captain369_grid_runs','uint32_t',runs(q['built']['grid'])),('captain369_node_words','uint32_t',q['built']['regions']),('captain369_filtered_words','uint32_t',q['filtered']['state']['regions']),('captain369_structure_positions','uint32_t',[w for r in q['sources']if r['type']!='captain'for w in r['words'][:2]]),('captain369_actor_position','uint32_t',next(r for r in q['sources']if r['type']=='captain')['words'][:2]),('captain369_initial_point','uint32_t',q['point_before'])]:out.append(array(name,kind,values))
 a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n\n'.join(out)+'\n');print(a.output)
if __name__=='__main__':main()
