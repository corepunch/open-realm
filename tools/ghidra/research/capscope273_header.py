#!/usr/bin/env python3
"""Emit literal original target/member scope expectations; never compute them."""
def header(original):
 rows=[r for r in original['rows']if r['target']not in('cached','retired')]
 out='/* Literal original169c50/169d60/16da60 words; generated by capscope273_header.py. */\nstatic struct {unsigned outer,drop,target;struct {unsigned attached,ready,counters[4];} stage[3][4];} const capscope273_rows[]={\n'
 for row in rows:
  stages=[]
  for ev in row['events']:
   event=[]
   for at in('acquire-enter','acquire-leave','release-enter','release-leave'):
    t=next(t for t in ev['trace']if t['at']==at)
    event.append('{%s,%s,{%s}}'%(sum(1<<i for i in t['attached']),sum(1<<i for i in t['ready']),','.join(map(str,t['counters']))))
   stages.append('{'+','.join(event)+'}')
  out+='{%d,%d,%d,{%s}},\n'%(row['outer'],row['drop'],('none','distinct','alias','invalid').index(row['target']),','.join(stages))
 return out+'};\n'
