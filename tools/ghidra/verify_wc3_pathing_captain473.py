#!/usr/bin/env python3
"""Verify the GROUP-03.4.7.3 retreat473 moving-roster retreat journeys, retail UI save/load and engine replay.

The immutable bundle holds every accepted raw observation and observer-free control of two
public families (retreat473: four removals; retreat473b: an extra removal during retreat) and
the retail UI save/load family. Validation replays them through retreat473_expected.freeze,
requires both committed engine literal headers to be regenerated byte-for-byte, checks the
recovered policy boundaries (removal reevaluation, retreat-member reissue, retained identical
member head, goal-event clear) and requires every retail load to resume identically to its
uninterrupted first pass, including saves inside the retreat bit window. main() additionally
guards the original instructions and runs the Classic/TFT engine tests.
"""
import argparse, gzip, hashlib, json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/frida/research'))
sys.path.insert(0, str(ROOT / 'tools/ghidra'))
import retreat473_expected as expected  # noqa: E402
import retreat473_saveload_compare as saveload  # noqa: E402

SPEC = ROOT / 'tools/ghidra/fixtures/retail-captain473-1.27.json'
HEADERS = {'retreat473': ROOT / 'games/warcraft-3/game/tests/fixtures/retail_retreat473.h',
           'retreat473b': ROOT / 'games/warcraft-3/game/tests/fixtures/retail_retreat473b.h'}
TESTS = ['wc3_captain_retreat473.*']
SHA = expected.HASH
HOME = expected.HOME
RETREAT_WINDOW = range(136, 144)  # resume ticks whose save point carries bit2 (set 135, cleared 143)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def removal_policy(fixture):
    calls, reissues = fixture['calls'], fixture['reissues']
    removal = [c for c in calls if c['tick'] == 135 and c['name'] == 'home-reevaluate']
    if [(c['caller'], c['result']) for c in removal] != [(0x9d790d, 0)] * 3 + [(0x9d790d, 1)]:
        raise ValueError('removal reevaluation sequence')
    if [c['flags'] for c in removal] != [[0x1001, 0x1001]] * 3 + [[0x1001, 0x1003]]:
        raise ValueError('retreat bit producer')
    if [c['counts'][1] for c in removal] != [5, 4, 3, 2]:
        raise ValueError('roster count at reevaluation')
    retreat = [r for r in reissues if r['tick'] == 135]
    if len(retreat) != 2 or any(r['caller'] != 0x9d180d or r['order'] != 851986 or r['target'] != '0x0' or r['point'] != HOME
                                for r in retreat):
        raise ValueError('retreat member reissue')
    home = [c for c in calls if c['tick'] == 135 and c['name'] == 'point-request']
    if len(home) != 1 or home[0]['request'] != HOME or home[0]['range'] != 0x43fa0000:
        raise ValueError('retreat home request')


def policy_a(fixture):
    removal_policy(fixture)
    calls = fixture['calls']
    if any(r['tick'] > 135 for r in fixture['reissues']):
        raise ValueError('unexpected later reissue')
    clear = [c for c in calls if c['name'] == 'go-home' and c['tick'] == 143]
    if len(clear) != 1 or clear[0]['caller'] != 0x9cff7d or clear[0]['flags'] != [0x1003, 0x1001]:
        raise ValueError('goal-event retreat clear')
    if any(c['name'] == 'point-request' and c['tick'] > 135 for c in calls):
        raise ValueError('near-home GoHome must not republish')
    final = [r for r in fixture['public'] if r[1] == 300]
    if [r[:3] for r in final] != [[u, 300, 0] for u in range(6)] or any(r[3] or r[4] for r in final[:4]) or \
            not all(r[3] and r[4] for r in final[4:]):
        raise ValueError('final public roster state')
    last = fixture['captain'][-1]
    if last[3] != 0x1001 or last[5] != 2 or last[15:] != [0, 0]:
        raise ValueError('final Captain state')


def policy_b(fixture):
    removal_policy(fixture)
    calls, reissues = fixture['calls'], fixture['reissues']
    second = [c for c in calls if c['tick'] == 139 and c['name'] == 'home-reevaluate']
    if len(second) != 1 or second[0]['caller'] != 0x9d790d or second[0]['result'] != 1 or \
            second[0]['flags'] != [0x1003, 0x1003] or second[0]['counts'][1] != 1:
        raise ValueError('second removal reevaluation')
    again = [r for r in reissues if r['tick'] == 139]
    if len(again) != 1 or again[0]['caller'] != 0x9d180d or again[0]['target'] != '0x0' or again[0]['point'] != HOME:
        raise ValueError('second retreat member reissue')
    republish = [c for c in calls if c['tick'] == 139 and c['name'] == 'point-request']
    if len(republish) != 1 or republish[0]['request'] != HOME or republish[0]['range'] != 0x43fa0000:
        raise ValueError('second retreat actor republication')
    clear = [c for c in calls if c['name'] == 'go-home' and c['caller'] == 0x9cff7d and c['tick'] > 135]
    if len(clear) != 1 or clear[0]['tick'] != 144 or clear[0]['flags'] != [0x1003, 0x1001]:
        raise ValueError('goal-event retreat clear')
    last = fixture['captain'][-1]
    if last[3] != 0x1001 or last[5] != 1 or last[15:] != [0, 0]:
        raise ValueError('final Captain state')


POLICY = {'retreat473': policy_a, 'retreat473b': policy_b}


def rows_of(capture):
    return [json.loads(l) for l in capture['raw_jsonl'].splitlines()]


def check_capture(capture, rows, role, map_sha):
    meta = rows[0]
    if meta.get('event') != 'metadata' or meta.get('sha256') != SHA:
        raise ValueError('capture metadata')
    if meta['mode'] != ('control' if role == 'control' else 'observe'):
        raise ValueError('capture mode')
    if meta['source_sha256']['map'] != map_sha:
        raise ValueError('map identity')
    if role == 'control' and any(r.get('event') in ('module', 'marker') for r in rows):
        raise ValueError('control is instrumented')
    pre = [x for x in rows if x.get('event') == 'preload-file']
    if len(pre) != 1 or not pre[0].get('complete'):
        raise ValueError('incomplete capture')
    if digest(capture['preload'].encode('utf-8')) != pre[0]['sha256']:
        raise ValueError('preload bytes differ from capture record')


def validate_family(family, header_text):
    caps = family['captures']
    roles = [c['role'] for c in caps]
    if roles.count('control') != 1 or roles.count('observation') < 2 or roles[-1] != 'control':
        raise ValueError('capture roles')
    rows = [rows_of(c) for c in caps]
    for c, r in zip(caps, rows):
        check_capture(c, r, c['role'], family['map_sha256'])
    fixture, header = expected.freeze([r for r, c in zip(rows, caps) if c['role'] == 'observation'], rows[-1],
                                      [c['preload'] for c in caps], family['name'])
    if header != header_text:
        raise ValueError('engine literal header differs from evidence ' + family['name'])
    POLICY[family['name']](fixture)
    return fixture, dict(observations=roles.count('observation'), controls=1, public_markers=fixture['markers'],
                         semantic_records=fixture['semantic_records'], semantic_sha256=fixture['semantic_sha256'],
                         public_rows=fixture['public_rows'], captain_snapshots=fixture['snapshots'])


def validate_saveload(family, accepted, map_sha):
    observed, controls = [], []
    for c in family['captures']:
        rows = rows_of(c)
        check_capture(c, rows, c['role'], map_sha)
        if c['role'] == 'observation':
            r = saveload.compare(rows, accepted['public'])
            if r['public_differences'] or r['policy_record_differences'] or r['captain_snapshot_differences'] or \
                    not r['first_pass_equals_accepted'] or not r['attack_snapshots_compared']:
                raise ValueError('observed retail load does not resume the uninterrupted journey ' + c['name'])
            observed.append(dict(name=c['name'], resumed_tick=r['resumed_tick'], saved_flags=r['saved_flags'],
                                 public_records=r['public_records'], policy_records=r['policy_records'],
                                 attack_snapshots=r['attack_snapshots_compared']))
        else:
            r = saveload.compare_control(c['preload'], accepted['control_markers'])
            if not r['second_equals_first_suffix'] or not r['first_pass_equals_accepted']:
                raise ValueError('control retail load does not resume the uninterrupted journey ' + c['name'])
            controls.append(dict(name=c['name'], resumed_tick=r['resumed_tick'], second_markers=r['second_markers']))
    if not any(o['resumed_tick'] in RETREAT_WINDOW and o['saved_flags'] == 0x1003 for o in observed):
        raise ValueError('observed save inside the retreat window required')
    if not any(c['resumed_tick'] in RETREAT_WINDOW for c in controls):
        raise ValueError('observer-free save inside the retreat window required')
    return dict(observations=observed, controls=controls)


def validate_runtime(bundle, headers, counts=None):
    result, fixtures = {}, {}
    for family in bundle['families']:
        fixtures[family['name']], result[family['name']] = validate_family(family, headers[family['name']])
    if sorted(result) != sorted(HEADERS):
        raise ValueError('family inventory')
    a = next(f for f in bundle['families'] if f['name'] == 'retreat473')
    accepted = dict(public=fixtures['retreat473']['public'],
                    control_markers=expected.preload_markers(a['captures'][-1]['preload'])[0])
    result['saveload'] = validate_saveload(bundle['saveload'], accepted, a['map_sha256'])
    if counts is not None and result != counts:
        raise ValueError('evidence counts or semantic digest')
    return result


def validate(spec):
    if spec.get('version') != 2 or spec.get('task') != 'GROUP-03.4.7.3' or spec.get('game_sha256') != SHA or \
            spec.get('engine_tests') != TESTS:
        raise ValueError('wrong retreat473 contract')
    if len(spec.get('instructions', {})) != spec['guard_count'] or len(spec['functions']) != 8:
        raise ValueError('complete original instruction inventory')
    for name, value in spec['pins'].items():
        if digest((ROOT / name).read_bytes()) != value:
            raise ValueError('source pin changed ' + name)
    raw = (ROOT / spec['bundle']).read_bytes()
    if digest(raw) != spec['bundle_sha256']:
        raise ValueError('raw bundle changed')
    bundle = json.loads(gzip.decompress(raw))
    result = validate_runtime(bundle, {k: v.read_text() for k, v in HEADERS.items()}, spec['counts'])
    return bundle, result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--binary', type=Path, required=True)
    p.add_argument('--report', type=Path, required=True)
    p.add_argument('--test-binary', type=Path, default=ROOT / 'build/bin/openwarcraft3-tests')
    p.add_argument('--data', type=Path, default=ROOT / 'build/tests')
    a = p.parse_args()
    if a.report.exists():
        p.error('fresh report required')
    spec = json.loads(SPEC.read_text())
    _, result = validate(spec)
    from verify_wc3_pathing_target_normalize218 import original_bytes
    original_bytes(a.binary, spec['instructions'])
    import wc3_pathfinding_engine_tests as runner
    engine = runner.run_engine(a.test_binary, a.data, a.report, TESTS, timeout=900)
    result.update(passed=True, status='verified', binary_sha256=SHA, instructions=len(spec['instructions']),
                  engine=engine, scope=spec['scope'])
    a.report.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result))


if __name__ == '__main__':
    main()
